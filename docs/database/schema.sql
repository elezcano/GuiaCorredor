CREATE TABLE IF NOT EXISTS "users" (
	"id" BIGSERIAL NOT NULL UNIQUE,
	"email" VARCHAR(255) NOT NULL UNIQUE,
	"password_hash" VARCHAR(255) NOT NULL,
	"first_name" VARCHAR(100) NOT NULL,
	"last_name" VARCHAR(100) NOT NULL,
	"phone" VARCHAR(50),
	"profile_photo_url" VARCHAR(500),
	"status" VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
	"created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	"updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	"last_login_at" TIMESTAMP,
	PRIMARY KEY("id")
);


CREATE UNIQUE INDEX "idx_users_email"
ON "users" ("email");

CREATE TABLE IF NOT EXISTS "companies" (
	"id" BIGSERIAL NOT NULL UNIQUE,
	"legal_name" VARCHAR(255) NOT NULL,
	"trade_name" VARCHAR(255),
	"country" VARCHAR(100) NOT NULL,
	"status" VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
	"created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	"updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY("id")
);


CREATE TABLE IF NOT EXISTS "memberships" (
	"id" BIGSERIAL NOT NULL UNIQUE,
	"user_id" BIGINT NOT NULL UNIQUE,
	"company_id" BIGINT NOT NULL UNIQUE,
	"role" VARCHAR(20) NOT NULL DEFAULT 'ADMIN',
	"status" VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
	"created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	"revoked_at" TIMESTAMP NOT NULL,
	PRIMARY KEY("id")
);


CREATE INDEX "idx_memberships_user_status"
ON "memberships" ("user_id", "status");

CREATE TABLE IF NOT EXISTS "company_billing" (
	"company_id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"billing_email" VARCHAR(255),
	"fiscal_adress" VARCHAR(500),
	"invoice_name" VARCHAR(255),
	"created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	"updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY("company_id")
);


